from __future__ import annotations

from pathlib import Path
from typing import Any, Protocol

from app.domain.lifecycle import ListCompleteResult, VectorDeleteResult
from app.domain.models import Asset, Job, JobStatus, ObjectEntry, Source
from app.domain.media import PreparedFrame, SamplePoint, SampleSettings, VideoInfo
from app.domain.subtitle import ParsedSubtitles


class MetadataRepository(Protocol):
    def add_source(self, source: Source, access_key: str | None, secret_key: str | None) -> Source: ...
    def list_sources(self) -> list[Source]: ...
    def get_source(self, source_id: str) -> Source | None: ...
    def get_source_credentials(self, source_id: str) -> tuple[str | None, str | None]: ...
    def update_source(self, source_id: str, **fields: Any) -> Source: ...
    def delete_source(self, source_id: str) -> None: ...
    def set_source_probe(self, source_id: str, status: str, message: str) -> Source: ...
    def upsert_asset(self, asset: Asset) -> Asset: ...
    def list_assets(self, source_id: str | None = None) -> list[Asset]: ...
    def get_asset(self, asset_id: str) -> Asset | None: ...
    def upsert_frame(self, asset_id: str, job_id: str, frame: PreparedFrame) -> None: ...
    def get_frame(self, asset_id: str, frame_index: int) -> dict[str, Any] | None: ...
    def list_frames(self, asset_id: str) -> list[dict[str, Any]]: ...
    def update_asset_status(self, asset_id: str, status: str): ...
    def get_platform_storage(self) -> Source | None: ...


class TaskRepository(Protocol):
    def add_job(self, job: Job) -> Job: ...
    def list_jobs(self, status: JobStatus | None = None) -> list[Job]: ...
    def get_job(self, job_id: str) -> Job | None: ...
    def update_job(self, job_id: str, **fields: Any) -> Job: ...
    def claim_next(self, worker_id: str, lease_seconds: int, *, lane: str | None = None) -> Job | None: ...
    def waiting_positions(self) -> dict[str, int]: ...
    def delete_job(self, job_id: str) -> None: ...


class SourceReader(Protocol):
    def probe(self, source: Source, access_key: str | None, secret_key: str | None) -> None: ...
    def list_prefix(
        self,
        source: Source,
        access_key: str | None,
        secret_key: str | None,
        prefix: str,
    ) -> list[ObjectEntry]: ...
    def download_readonly(
        self,
        source: Source,
        access_key: str | None,
        secret_key: str | None,
        object_key: str,
        dest_path: Path,
    ) -> Path: ...
    def list_complete(
        self,
        source: Source,
        access_key: str | None,
        secret_key: str | None,
        prefix: str = "",
    ) -> ListCompleteResult: ...


class FileStore(Protocol):
    def available(self) -> bool: ...
    def status_message(self) -> str: ...
    def exists(self, key: str) -> bool: ...
    def put_bytes(self, key: str, data: bytes, content_type: str) -> str: ...
    def get_bytes(self, key: str) -> bytes: ...
    def head(self, key: str) -> dict[str, Any]: ...
    def get_range(self, key: str, start: int, end: int) -> bytes: ...
    def put_stream(self, key: str, stream: Any, content_type: str, *, overwrite: bool = False) -> str: ...
    def delete_object(self, key: str) -> bool: ...
    def delete_objects(self, keys: list[str]) -> list[str]: ...


class FrameSampler(Protocol):
    def probe(self, path: Path) -> VideoInfo: ...
    def plan(self, info: VideoInfo, settings: SampleSettings) -> list[SamplePoint]: ...
    def extract_one(self, path: Path, point: SamplePoint) -> bytes: ...


class FrameCleaner(Protocol):
    def inspect(self, image_bytes: bytes, settings: SampleSettings, last_kept_signature: list[float] | None) -> dict: ...


class VectorIndex(Protocol):
    def available(self) -> bool: ...
    def status_message(self) -> str: ...
    def delete_vectors(self, refs: list) -> VectorDeleteResult: ...
    def delete_by_asset(self, asset_id: str, collections: list[str] | None = None) -> VectorDeleteResult: ...
    def upsert_records(self, modality: str, records: list[dict]) -> int: ...
    def search(self, modality: str, vector: list[float], *, limit: int, offset: int = 0, filter_expr: str | None = None) -> list[dict]: ...


class ImageTextEncoder(Protocol):
    def available(self) -> bool: ...
    def status_message(self) -> str: ...
    def encode_text(self, text: str) -> list[float]: ...
    def encode_image(self, image_bytes: bytes) -> list[float]: ...


class SubtitleEncoder(Protocol):
    def available(self) -> bool: ...
    def status_message(self) -> str: ...
    def encode_text(self, text: str) -> list[float]: ...


class SubtitleParser(Protocol):
    def parse_bytes(self, data: bytes, filename: str) -> ParsedSubtitles: ...


class AuthorizationPolicy(Protocol):
    def auth_enabled(self) -> bool: ...
    def allow(self, identity, action: str, resource=None) -> bool: ...


class FaceRecognizer(Protocol):
    def available(self) -> bool: ...
    def status_message(self) -> str: ...
    def public_status(self) -> dict[str, Any]: ...
    def detect_and_encode(self, image_bytes: bytes) -> list[Any]: ...
